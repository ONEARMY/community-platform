CREATE OR REPLACE FUNCTION public.get_subscribed_users_emails_to_notify(p_content_id bigint, p_content_type text)
 RETURNS TABLE(
    email character varying,
    profile_id bigint,
    profile_created_at timestamp with time zone,
    display_name character varying,
    comments boolean,
    replies boolean,
    research_updates boolean,
    is_unsubscribed boolean
)
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
BEGIN
    RETURN QUERY
    SELECT DISTINCT ON (p.id)
        u.email,
        p.id AS profile_id,
        p.created_at AS profile_created_at,
        p.display_name::character varying,
        np.comments,
        np.replies,
        np.research_updates,
        np.is_unsubscribed
    FROM subscribers s
    INNER JOIN profiles p ON s.user_id = p.id
    INNER JOIN auth.users u ON p.auth_id = u.id
    LEFT JOIN notifications_preferences np ON np.user_id = p.id
    WHERE s.content_id = p_content_id AND s.content_type = p_content_type
    ORDER BY p.id;
END;
$function$
;

REVOKE EXECUTE ON FUNCTION "public"."get_subscribed_users_emails_to_notify"(bigint, "text") FROM PUBLIC, "anon";

CREATE OR REPLACE FUNCTION "public"."notify_all_profiles"(
  "p_tenant_id" "text",
  "p_action_type" "public"."notification_action_types",
  "p_content_type" "public"."notification_content_types",
  "p_content_id" bigint,
  "p_title" "text",
  "p_triggered_by_id" bigint
)
    RETURNS void
    LANGUAGE "sql"
    SET search_path = public, pg_temp
    AS $$
  INSERT INTO notifications (action_type, content_type, content_id, title, triggered_by_id, owned_by_id, is_read, tenant_id)
  SELECT p_action_type, p_content_type, p_content_id, p_title, p_triggered_by_id, p.id, false, p_tenant_id
  FROM profiles p
  WHERE p.tenant_id = p_tenant_id;
$$;

REVOKE EXECUTE ON FUNCTION "public"."notify_all_profiles"("text", "public"."notification_action_types", "public"."notification_content_types", bigint, "text", bigint) FROM PUBLIC, "anon";
